rail3 = [(450, 182), (500, 171), (550, 166), (600, 164), (650, 163), (700, 166), (740, 172)]
def interp(tab, y):
    for (y0, x0), (y1, x1) in zip(tab, tab[1:]):
        if y0 <= y <= y1: return x0 + (x1 - x0) * (y - y0) / (y1 - y0)
yori = []
for y in range(455, 741, 24):
    yori.append((interp(rail2, y), y)); yori.append((interp(rail3, min(740, y + 12)), min(740, y + 12)))
LCD = dict(x0=300, x1=865, y0=375, y1=850)
inl = lambda x, y: LCD["x0"] - 4 < x < LCD["x1"] + 4 and LCD["y0"] - 4 < y < LCD["y1"] + 4
pins = [p for p in pins if not inl(*p)]
