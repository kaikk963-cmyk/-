# 釘配置図（参照画像の座標）から、盤面の定数（盤面の座標）を作る。縮尺は一様（ゆがめない）
import json, sys, math
nails = json.load(open(sys.argv[1]))
O = (79, 158); S = 300 / 949
T = lambda x, y: [round((x - O[0]) * S, 2), round((y - O[1]) * S, 2)]
TL = lambda pts: [T(*p) for p in pts]
# 見出し文字の誤検出を除き、薄いグレーで検出できなかった釘を足す
pins = [(x, y) for x, y in nails if not (x > 300 and y < 340)]
for q in [(228, 330), (232, 341), (110, 775), (118, 783), (150, 800), (157, 808)]:
    if all((q[0] - x) ** 2 + (q[1] - y) ** 2 > 8 ** 2 for x, y in pins): pins.append(q)  # 検出済みと重なるものは足さない
# 命釘（ヘソの真上の2本）は開きの設定で動かすので図の位置からは外す
pins = [(x, y) for x, y in pins if not (abs(y - 1075) < 6 and abs(x - 557) < 20)]
# 左の寄り釘：図の2本のレール（目盛りの点）
